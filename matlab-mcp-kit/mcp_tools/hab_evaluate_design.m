function hab_evaluate_design(nHAB, ringRadius_km, nChannels, sigmaSync_ns, dfOption, altBandHalf_km)
%HAB_EVALUATE_DESIGN MCP custom tool: cost/coverage/SWaP of a HAB constellation.
if nHAB < 3 || nHAB > 8, disp(jsonencode(struct('error','nHAB must be 3-8'))); return; end
if ~any(nChannels == [8 16 32 64]), disp(jsonencode(struct('error','nChannels must be 8, 16, 32 or 64'))); return; end
if ringRadius_km < 20 || ringRadius_km > 120, disp(jsonencode(struct('error','ringRadius_km must be 20-120'))); return; end
if sigmaSync_ns < 5 || sigmaSync_ns > 100, disp(jsonencode(struct('error','sigmaSync_ns must be 5-100'))); return; end
if altBandHalf_km < 3 || altBandHalf_km > 4.5, disp(jsonencode(struct('error','altBandHalf_km must be 3-4.5'))); return; end
d = struct('nHAB', round(nHAB), 'ringRadius_km', ringRadius_km, 'nChannels', nChannels, ...
    'sigmaSync_ns', sigmaSync_ns, 'dfOption', double(logical(dfOption)), 'altBandHalf_km', altBandHalf_km);
M = pw.evaluateDesign(d, struct('gridStep_km', 25));
out = struct('design', d, 'cost_USD', round(M.cost_USD), ...
    'effGeoCoverage', round(1000*M.effGeoCoverage)/1000, ...
    'coverage_fixed', round(1000*M.perClass(1).coverGeo)/1000, ...
    'coverage_marine', round(1000*M.perClass(2).coverGeo)/1000, ...
    'coverage_airborne', round(1000*M.perClass(3).coverGeo)/1000, ...
    'fracOnStation', round(1000*M.fracOnStation)/1000, ...
    'payloadMass_kg', round(100*M.payloadMass_kg)/100, 'payloadPower_W', round(10*M.payloadPower_W)/10, ...
    'feasible', logical(M.feasible), 'note', 'NOTIONAL seminar model');
disp(jsonencode(out));
end
