function [ctf, endpoint] = buildHabMcpServer(server)
%BUILDHABMCPSERVER Package the HAB EMSO tools and resources as one MCP
%   server on MATLAB Production Server (MCP Framework for MATLAB
%   Production Server, R2025b+ with MATLAB Compiler SDK).
%
%   ctf = buildHabMcpServer()                         build only
%   [ctf, endpoint] = buildHabMcpServer("http://localhost:9910")  build + deploy
%
%   Clients then connect to  <server>/HabEmso/mcp
%   Pattern follows the framework's Materials and MultiTool examples.
arguments
    server (1,1) string = ""
end
setupPaths;
here = fileparts(mfilename('fullpath'));
files = exportResources();

fcn = ["listEmitterTypes", "habInterceptRange", "habGeolocationAccuracy", ...
       "evaluateHabDesign", "identifyEmitter"];
% Example calls let the framework observe input/output types (argument
% blocks already declare them; examples add struct/JSON detail).
ex = { @() listEmitterTypes(), ...
       @() habInterceptRange("MAR-X1", 20, "side"), ...
       @() habGeolocationAccuracy("FIX-S1", 4, 45, -140, -20, "both"), ...
       @() evaluateHabDesign(4, 45, 32, 30, 0, 4), ...
       @() identifyEmitter(9.4, 0.5, 500, "rotating", 2.5) };

res = [ ...
  struct('uri', 'mcp://hab-emso/emitter_library', 'contents', files{1}, ...
         'name', 'emitter_library', 'title', 'Notional emitter library', ...
         'description', ['Parameters of the notional fixed, marine and airborne radar ' ...
                         'emitters used by every tool. Read this before choosing emitter IDs.'], ...
         'mimeType', 'application/json'), ...
  struct('uri', 'mcp://hab-emso/receiver', 'contents', files{2}, ...
         'name', 'receiver_notional', 'title', 'Notional filter-bank detector', ...
         'description', ['What the balloon payload measures (and does not): channels, ' ...
                         'sensitivity, clock error, SWaP. Notional, not vendor data.'], ...
         'mimeType', 'application/json') ];

ctf = prodserver.mcp.build(fcn, example=ex, archive="HabEmso", ...
    resource=res, folder=fullfile(here, "deploy"));
endpoint = "";
if strlength(server) > 0
    endpoint = prodserver.mcp.deploy(ctf, server);
    prodserver.mcp.ping(endpoint)
end
end
